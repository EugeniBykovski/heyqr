/**
 * Generates src/caption-metrics.ts: each caption font face's advance widths (thousandths of an em) for the scripts
 * captions use, read from the shipped files in public/caption-fonts. The renderer wraps captions with these numbers, so
 * the browser preview and the server's SVG / PNG get the same line breaks without loading fonts.
 * Run after changing caption fonts: pnpm fonts:metrics
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CAPTION_FONTS, LEGACY_CAPTION_FONT } from "../src/caption-fonts";
import { readTtf } from "../test/ttf-cmap";

const ROOT = path.resolve(import.meta.dirname, "../../..");
const RANGES: [number, number][] = [
  [0x20, 0x24f], // Latin, Latin-1, Latin Extended A/B
  [0x2b0, 0x36f], // spacing modifiers, combining diacritical marks
  [0x400, 0x52f], // Cyrillic and supplement
  [0x1e00, 0x1eff], // Latin Extended Additional (Vietnamese)
  [0x2000, 0x206f], // general punctuation
  [0x20a0, 0x20cf], // currency
  [0x2100, 0x214f], // letterlike symbols
  [0x2190, 0x21ff], // arrows
];

const files = [...new Set([...Object.values(CAPTION_FONTS), LEGACY_CAPTION_FONT].flatMap((f) => Object.values(f.faces)))].sort();
const out: Record<string, { fallback: number; runs: [number, number[]][] }> = {};
for (const file of files) {
  const ttf = readTtf(new Uint8Array(readFileSync(path.join(ROOT, "public/caption-fonts", file))));
  const em = (units: number) => Math.round((units * 1000) / ttf.unitsPerEm);
  const runs: [number, number[]][] = [];
  for (const [from, to] of RANGES)
    for (let c = from; c <= to; c++) {
      const adv = ttf.advances.get(c);
      if (adv === undefined) continue;
      const last = runs.at(-1);
      if (last && last[0] + last[1].length === c) last[1].push(em(adv));
      else runs.push([c, [em(adv)]]);
    }
  // Characters the face lacks (emoji, other scripts) are drawn by a fallback font; they are measured as the face's
  // widest common letter so wrapping errs towards an earlier break.
  out[file] = { fallback: em(Math.max(ttf.advances.get(0x4d) ?? 0, ttf.advances.get(0x416) ?? 0, ttf.unitsPerEm * 0.6)), runs };
}
writeFileSync(
  path.join(ROOT, "packages/qr-core/src/caption-metrics.ts"),
  `// Generated by packages/qr-core/scripts/caption-metrics.ts from public/caption-fonts. Do not edit; run pnpm fonts:metrics.\n` +
    `/** Advance widths in thousandths of an em: per face file, runs of consecutive code points [first, widths]. */\n` +
    `export const CAPTION_METRICS: Record<string, { fallback: number; runs: [number, number[]][] }> = ${JSON.stringify(out)};\n`,
);
console.log(`caption-metrics: ${files.length} faces`);
